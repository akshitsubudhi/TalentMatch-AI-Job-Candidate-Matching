"use client";

import { useCallback, useEffect, useState } from "react";
import type { ExplanationResponse } from "@/lib/types";
import { Badge, Skeleton } from "./ui";

type State =
  | { status: "loading" }
  | { status: "ready"; data: ExplanationResponse["data"] }
  | { status: "error"; message: string };

/** Fetches (or reads from cache) the "why this fits" explanation for one pair. */
export function ExplanationPanel({ jobId, candidateId }: { jobId: string; candidateId: string }) {
  const [state, setState] = useState<State>({ status: "loading" });

  const load = useCallback(
    async (signal?: AbortSignal) => {
      setState({ status: "loading" });
      try {
        const res = await fetch("/api/explanations", {
          method: "POST",
          headers: { "content-type": "application/json" },
          body: JSON.stringify({ jobId, candidateId }),
          signal,
        });
        const body = (await res.json()) as ExplanationResponse | { error: { message: string } };
        if (!res.ok || "error" in body) {
          setState({ status: "error", message: "error" in body ? body.error.message : `Request failed (${res.status})` });
          return;
        }
        setState({ status: "ready", data: body.data });
      } catch (err) {
        if ((err as Error).name === "AbortError") return;
        setState({ status: "error", message: "Network error while loading the explanation" });
      }
    },
    [jobId, candidateId],
  );

  useEffect(() => {
    const controller = new AbortController();
    void load(controller.signal);
    return () => controller.abort();
  }, [load]);

  if (state.status === "loading") {
    return (
      <div className="space-y-2" aria-busy="true" aria-label="Generating explanation">
        <Skeleton className="h-3 w-full" />
        <Skeleton className="h-3 w-11/12" />
        <Skeleton className="h-3 w-2/3" />
      </div>
    );
  }

  if (state.status === "error") {
    return (
      <div className="flex flex-wrap items-center gap-3 text-sm text-rose-700 dark:text-rose-300" role="alert">
        <span>Couldn&apos;t load the explanation: {state.message}</span>
        <button type="button" onClick={() => void load()} className="rounded-md border border-current px-2 py-0.5 text-xs">
          Retry
        </button>
      </div>
    );
  }

  const { data } = state;
  const isRules = data.model === "rule-based";
  return (
    <div className="space-y-3">
      <p className="text-sm leading-relaxed text-slate-700 dark:text-slate-300">{data.summary}</p>
      <div className="grid gap-3 sm:grid-cols-2">
        <SkillGroup title="Matched skills" skills={data.matched_skills} tone="green" empty="None of the listed skills" />
        <SkillGroup title="Missing skills" skills={data.missing_skills} tone="red" empty="No gaps among listed skills" />
      </div>
      <p className="text-xs text-slate-500">
        {isRules ? "Rule-based explanation (no LLM configured)" : `Generated by ${data.model}`} · {data.prompt_version}
        {data.cached ? " · cached" : " · just generated"}
      </p>
    </div>
  );
}

function SkillGroup({ title, skills, tone, empty }: { title: string; skills: string[]; tone: "green" | "red"; empty: string }) {
  return (
    <div>
      <h4 className="mb-1 text-xs font-semibold uppercase tracking-wide text-slate-500">{title}</h4>
      {skills.length === 0 ? (
        <p className="text-xs text-slate-500">{empty}</p>
      ) : (
        <ul className="flex flex-wrap gap-1.5">
          {skills.map((s) => (
            <li key={s}>
              <Badge tone={tone}>{s}</Badge>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
