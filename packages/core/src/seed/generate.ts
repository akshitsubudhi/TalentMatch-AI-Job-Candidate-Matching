import { SENIORITIES, type CandidateUploadFields, type JobCreateInput, type Seniority } from "../schemas";
import {
  COMPANY_PREFIXES,
  COMPANY_SUFFIXES,
  DEGREES,
  FAMILIES,
  FIRST_NAMES,
  IMPLIED,
  LAST_NAMES,
  LOCATIONS,
  OUTCOMES,
  SENIORITY_TITLE,
  SENIORITY_YEARS,
  SPELLINGS,
  type RoleFamily,
} from "./data";

export const SYNTHETIC_RESUME_HEADER = "[SYNTHETIC RESUME - generated by the TalentMatch seed script; not a real person]";
export const SYNTHETIC_JOB_FOOTER = "(Synthetic job post generated by the TalentMatch seed script; the company is fictional.)";

/** Small, fast, deterministic PRNG (mulberry32). */
export function createRng(seed: number) {
  let a = seed >>> 0;
  const next = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const int = (min: number, max: number) => min + Math.floor(next() * (max - min + 1));
  const pick = <T>(items: readonly T[]): T => items[Math.floor(next() * items.length)] as T;
  const shuffle = <T>(items: readonly T[]): T[] => {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
      const j = Math.floor(next() * (i + 1));
      [out[i], out[j]] = [out[j] as T, out[i] as T];
    }
    return out;
  };
  const sample = <T>(items: readonly T[], n: number): T[] => shuffle(items).slice(0, Math.min(n, items.length));
  return { next, int, pick, shuffle, sample, chance: (p: number) => next() < p };
}
export type Rng = ReturnType<typeof createRng>;

export interface SeedJob {
  index: number;
  family: string;
  input: JobCreateInput;
}

export interface SeedCandidate {
  index: number;
  family: string;
  /** Ground truth: every skill this synthetic person has (named or only implied in the text). */
  trueSkills: string[];
  /** Skills that appear by name/alias in the text. */
  explicitSkills: string[];
  fields: CandidateUploadFields;
  resumeText: string;
}

export interface SeedDataset {
  seed: number;
  jobs: SeedJob[];
  candidates: SeedCandidate[];
}

function mention(rng: Rng, skill: string): string {
  const spellings = SPELLINGS[skill] ?? [];
  return spellings.length > 0 && rng.chance(0.3) ? rng.pick(spellings) : skill;
}

function familySeniority(rng: Rng): Seniority {
  // Weighted toward mid/senior like a real applicant pool.
  const r = rng.next();
  if (r < 0.04) return "intern";
  if (r < 0.2) return "junior";
  if (r < 0.5) return "mid";
  if (r < 0.82) return "senior";
  if (r < 0.95) return "lead";
  return "principal";
}

function company(rng: Rng): string {
  return `${rng.pick(COMPANY_PREFIXES)} ${rng.pick(COMPANY_SUFFIXES)}`;
}

function titleFor(seniority: Seniority, title: string): string {
  const prefix = SENIORITY_TITLE[seniority];
  return prefix ? `${prefix} ${title}` : title;
}

function generateJob(rng: Rng, index: number): SeedJob {
  const family = rng.pick(FAMILIES);
  const seniority = rng.pick(SENIORITIES.filter((s) => s !== "intern" || rng.chance(0.3)));
  const required = rng.sample(family.core, rng.int(5, 7));
  const niceToHave = rng.sample(
    family.optional.filter((s) => !required.includes(s)),
    rng.int(1, 2),
  );
  const title = titleFor(seniority, rng.pick(family.titles));
  const org = company(rng);
  const location = rng.pick(LOCATIONS);
  const [y0, y1] = SENIORITY_YEARS[seniority];

  // Job posts name their skills explicitly (as real postings do). They never reuse the
  // IMPLIED phrases from resumes, which would leak exact text overlap into the benchmark.
  const responsibilities = [
    `- Design, build and operate ${rng.pick(family.mission)} with ${required[0]} and ${required[1]}.`,
    `- Raise the bar on quality and delivery using ${required[2]}.`,
    `- Own technical decisions end to end, ${rng.pick(OUTCOMES)}.`,
  ];
  const description = [
    `${org} is hiring a ${title} to own ${rng.pick(family.mission)}.`,
    "",
    "What you'll do:",
    ...responsibilities,
    `- Collaborate with product, design and engineering, ${rng.pick(OUTCOMES)}.`,
    "",
    "What we're looking for:",
    `- ${y0}-${y1}+ years of relevant experience.`,
    `- Hands-on experience with ${required.slice(0, -1).join(", ")} and ${required.at(-1)}.`,
    `- Nice to have: ${niceToHave.join(", ")}.`,
    "",
    `Location: ${location}.`,
    SYNTHETIC_JOB_FOOTER,
  ].join("\n");

  return { index, family: family.key, input: { title, description, location, seniority, skills: required } };
}

function generateCandidate(rng: Rng, index: number): SeedCandidate {
  // ~15% career-switchers whose skills straddle two families.
  const family = rng.pick(FAMILIES);
  const secondary: RoleFamily | null = rng.chance(0.15) ? rng.pick(FAMILIES.filter((f) => f.key !== family.key)) : null;
  const seniority = familySeniority(rng);
  const [y0, y1] = SENIORITY_YEARS[seniority];
  const years = rng.int(y0, y1);

  const coreCount = rng.int(4, 8);
  const trueSkills = new Set<string>(rng.sample(family.core, coreCount));
  for (const s of rng.sample(family.optional, rng.int(0, 2))) trueSkills.add(s);
  if (secondary) for (const s of rng.sample(secondary.core, rng.int(2, 4))) trueSkills.add(s);

  // Each skill is either named (keyword-visible) or only described (keyword-invisible).
  const explicit: string[] = [];
  const implied: string[] = [];
  for (const s of trueSkills) (rng.chance(0.65) ? explicit : implied).push(s);
  if (explicit.length === 0) explicit.push(implied.pop() as string);

  const name = `${rng.pick(FIRST_NAMES)} ${rng.pick(LAST_NAMES)}`;
  const location = rng.pick(LOCATIONS);
  const headline = `${titleFor(seniority, family.headline)}${secondary ? ` moving into ${secondary.headline.toLowerCase()} work` : ""}`;

  const roleCount = Math.max(1, Math.min(5, Math.ceil(years / 3) + rng.int(0, 1)));
  const statements = rng.shuffle([
    ...explicit.map((s) => ({ kind: "explicit" as const, skill: s })),
    ...implied.map((s) => ({ kind: "implied" as const, skill: s })),
  ]);

  const roles: string[] = [];
  let cursor = 0;
  let yearEnd = 2026;
  for (let r = 0; r < roleCount; r++) {
    const span = Math.max(1, Math.round(years / roleCount));
    const start = yearEnd - span;
    const perRole = Math.max(2, Math.ceil(statements.length / roleCount));
    const bullets: string[] = [];
    for (let b = 0; b < perRole && cursor < statements.length; b++, cursor++) {
      const st = statements[cursor]!;
      bullets.push(
        st.kind === "explicit"
          ? `- Used ${mention(rng, st.skill)} to deliver ${rng.pick(family.mission)}, ${rng.pick(OUTCOMES)}.`
          : `- ${capitalise(IMPLIED[st.skill] ?? "")}, ${rng.pick(OUTCOMES)}.`,
      );
    }
    // Generic filler makes senior resumes long enough to need several chunks.
    for (let f = 0; f < rng.int(1, 3); f++) {
      bullets.push(`- ${rng.pick(FILLERS)}, ${rng.pick(OUTCOMES)}.`);
    }
    roles.push(
      [`${r === 0 ? titleFor(seniority, rng.pick(family.titles)) : rng.pick(family.titles)} - ${company(rng)} (${start}-${r === 0 ? "present" : yearEnd})`, ...bullets].join("\n"),
    );
    yearEnd = start;
  }

  const skillsLine = rng.shuffle(explicit).map((s) => mention(rng, s));
  const resumeText = [
    SYNTHETIC_RESUME_HEADER,
    name,
    `${headline} | ${location}`,
    "",
    "Summary",
    `${capitalise(family.headline)} with ${years} year${years === 1 ? "" : "s"} of experience building ${rng.pick(family.mission)}.`,
    "",
    "Experience",
    roles.join("\n\n"),
    "",
    "Skills",
    skillsLine.join(", "),
    "",
    "Education",
    rng.pick(DEGREES),
  ].join("\n");

  return {
    index,
    family: family.key,
    trueSkills: [...trueSkills],
    explicitSkills: explicit,
    fields: { fullName: name, location, seniority, headline, skills: [] },
    resumeText,
  };
}

export function generateDataset(options: { seed?: number; jobs?: number; candidates?: number } = {}): SeedDataset {
  const seed = options.seed ?? 42;
  const rng = createRng(seed);
  const jobs = Array.from({ length: options.jobs ?? 200 }, (_, i) => generateJob(rng, i));
  const candidates = Array.from({ length: options.candidates ?? 500 }, (_, i) => generateCandidate(rng, i));
  return { seed, jobs, candidates };
}

const FILLERS = [
  "Partnered with cross-functional teams on quarterly planning",
  "Led incident reviews and wrote follow-up action plans",
  "Interviewed and onboarded new team members",
  "Documented architecture decisions for the wider organisation",
  "Presented project results at internal all-hands meetings",
  "Worked closely with customers to prioritise feedback",
];

function capitalise(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
